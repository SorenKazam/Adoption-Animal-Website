export function getSelectedPhoneCountryCodes(selectedCountries: string[]) {
  const set = new Set(
    selectedCountries.map((country) =>
      country.toLowerCase().replace(/^./, (c) => c.toUpperCase()),
    ),
  );

  return PHONE_COUNTRY_CODES.filter((country) => set.has(country.countryName));
}
